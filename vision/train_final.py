from ultralytics import YOLO

# 1. 모델 로드 (YOLOv11 나노 모델)
model = YOLO('yolo11n.pt')

# 2. 학습 시작
model.train(
    # 📍 경로 설정 (수정 완료된 절대 경로)
    data='/Users/gwonchangbin/univ/2-1/임베디드인공지능최적화/4WD_4wheelguys/vision/Final_Datasetv4/data.yaml',
    plots=True,
    # ==========================================
    # 🏎️ 1. 하드웨어 및 학습 기본 설정 (M3 Pro 최적화 유지)
    # ==========================================
    epochs=200,         
    patience=25,        
    imgsz=640,          
    device='mps',       
    batch=32,           
    workers=8,          
    cache=True,         
    verbose=True,       

    # ==========================================
    # ☀️ 2. 환경 적응 (빛, 색상, 스케일) 증강
    # ==========================================
    hsv_h=0.015,       
    hsv_s=0.7,         
    hsv_v=0.4,         
    scale=0.9,         # [수정] 0.8 -> 0.9 (가까워졌을 때 거대해지는 이미지 커버)
    translate=0.1,     # [수정] 0.05 -> 0.1 (코앞에서 화면 구석으로 밀려날 때 대응)
    mosaic=0.5,        # [핵심수정] 1.0 -> 0.3 (화살표가 선명한 단독 큰 이미지 비율 대폭 상향)

    # ==========================================
    # 📐 3. 주행 역학 (화살표 방향성 보존을 위해 보수적 변경)
    # ==========================================
    degrees=4.0,       # [수정] 10.0 -> 4.0 (과도한 회전으로 인한 화살표 방향 오염 방지)
    perspective=0.002, # [수정] 0.001 -> 0.002 (코앞 렌즈 왜곡 아주 살짝만 반영)
    shear=0.3,         # [핵심수정] 1.0 -> 0.1 (화살표 형태가 찌그러져 타 클래스로 오인되는 것 방지)

    # ==========================================
    # ⛔ 4. 방향성 파괴 방지 및 맷집 보완
    # ==========================================
    fliplr=0.0,        # 좌우 반전 절대 금지 (유지)
    flipud=0.0,        # 상하 반전 절대 금지 (유지)
    erasing=0.0,       # 화살표 파괴 방지를 위해 절대 금지 (유지)
    mixup=0.0,         
    copy_paste=0.0,
    
    # 📂 저장 위치 설정
    project='vision/runs/detect/4WD_Final_Project',
    name='train_data_0526'
)

