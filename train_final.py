from ultralytics import YOLO

# 1. 모델 로드 (YOLOv11 나노 모델)
model = YOLO('yolo11n.pt')

# 2. 학습 시작
model.train(
    # 📍 경로 설정 (수정 완료된 절대 경로)
    data='/Users/gwonchangbin/univ/2-1/임베디드인공지능최적화/4WD_4wheelguys/Final_Datasetv2/data.yaml',
    
    # ⚙️ 기본 학습 설정
    epochs=300,         # (수정) 혹독한 증강을 소화하기 위해 에포크를 늘립니다.
    patience=20,        # (추가) 20번 연속으로 성적이 안 오르면 알아서 조기 종료합니다.
    imgsz=[480, 640],          # [480, 640]으로 쓰셔도 되지만, 보통 정사각형(640)이 표준입니다.
    device='mps',       # 맥북 M3 Pro GPU 가속
    batch=32,           # 한 번에 처리할 사진 수 (M3 Pro 메모리에 맞게 16~32 추천)
    workers=8,          # 데이터 로딩 속도 향상
    cache=True,         # RAM에 데이터를 올려둬서 학습 속도 부스팅
    verbose=True,
    
    # 🛡️ 데이터 증강 설정 (방향 표지판 보호 및 실전 훈련 강화)
    # 1. 빛(조명) 대응: 실내 조명 반사 및 외부광 대응
    hsv_h=0.015,       # 색상 변화 (작게 유지)
    hsv_s=0.7,         # 채도 변화 (빛에 바랜 느낌 학습)
    hsv_v=0.4,         # 명도 변화 (밝고 어두운 환경 적응)
    
    # 2. 원거리/공간감 대응: 넓은 경기장 환경
    scale=0.8,         # 0.5보다 높여서 아주 작은 표지판부터 큰 표지판까지 폭넓게 학습
    translate=0.1,     # 표지판이 화면 가장자리에 걸리는 경우 대비
    mosaic=1.0,        # 여러 이미지를 합쳐 작은 객체 인식 성능 극대화 (필수)
    mixup=0.1,         # (추가) 두 이미지를 겹쳐서 복잡한 배경 속 객체 탐지 능력 향상
    
    # 3. 각도 및 가려짐 대응
    degrees=10.0,      # 로봇이 흔들릴 때 발생하는 미세한 회전 대응
    perspective=0.001, # 다가갈 때 발생하는 투영 변형 강화
    erasing=0.4,       # 그림자나 장애물에 일부가 가려진 표지판 학습
    
    # 4. 방향성 보호 (절대 수정 금지)
    fliplr=0.0,        # 좌우 반전 금지 (좌회전/우회전 구분)
    flipud=0.0,        # 상하 반전 금지 (실제 상황에서 거의 발생하지 않음)
    
    # 👇 새로 추가된 강력한 옵션
    shear=2.0,         # 코너링 시 찌그러지는 표지판 대비
    copy_paste=0.1,    # 표지판을 다른 배경에 합성하여 인지도 상승
    
    # 📂 저장 위치 설정
    project='4WD_Final_Project',
    name='train_1045_data'
)

print("✅ 학습이 성공적으로 시작되었습니다!")