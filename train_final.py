from ultralytics import YOLO

# 1. 모델 로드 (YOLOv11 나노 모델)
model = YOLO('yolo11n.pt')

# 2. 학습 시작
model.train(
    # 📍 경로 설정 (수정 완료된 절대 경로)
    data='/Users/gwonchangbin/univ/2-1/임베디드인공지능최적화/4WD_4wheelguys/Final_Datasetv3/data.yaml',
    
    # ==========================================
    # ⚙️ 1. 기본 학습 및 하드웨어 최적화 세팅
    # ==========================================
    epochs=300,         # (최대 학습 횟수) 강력한 데이터 증강을 모델이 완전히 소화할 수 있도록 충분한 시간을 부여합니다.
    patience=20,        # (조기 종료) 20번의 에포크 동안 인식률 개선이 없으면 더 이상 학습이 무의미하다고 판단하고 스스로 멈춥니다.
    imgsz=640,          # (입력 해상도) M3 Pro의 성능을 활용해 최고 시력(640)으로 학습하여 미세한 선과 표지판을 정확히 인지합니다.
    device='mps',       # (GPU 가속) 애플 실리콘(MacBook)의 통합 메모리와 GPU를 100% 활용하여 학습 속도를 극대화합니다.
    batch=32,           # (배치 사이즈) 한 번에 메모리에 올릴 사진 수. M3 Pro 메모리 효율의 스위트 스팟입니다.
    workers=8,          # (데이터 로딩) 8개의 스레드가 일꾼처럼 데이터를 미리 가져와서 GPU가 쉬지 않고 일하게 만듭니다.
    cache=True,         # (RAM 캐싱) 이미지 데이터를 RAM에 상주시켜 디스크 읽기 속도에 의한 병목을 제거합니다.
    verbose=True,       # 학습 진행 상황을 터미널에 상세히 출력합니다.

    # ==========================================
    # ☀️ 2. 환경 적응 (빛, 색상, 스케일) 증강
    # ==========================================
    hsv_h=0.015,       # (색상 변형) 표지판 고유의 색(빨/초)을 잃지 않도록 아주 미세하게만 변경합니다.
    hsv_s=0.7,         # (채도 변형) 조명 반사로 인해 표지판 색이 바래 보이거나 짙어 보이는 현상에 대비합니다.
    hsv_v=0.4,         # (명도 변형) 트랙의 그늘진 곳이나 밝은 형광등 아래에서도 표지판을 알아볼 수 있게 합니다.
    scale=0.8,         # (크기 변형) 멀리 있는 콩알만 한 표지판부터 코앞의 거대한 표지판까지 스케일 변화에 적응시킵니다.
    translate=0.05,     # (위치 이동) [핵심] 표지판이 카메라 렌즈 가장자리에 겨우 걸쳐 있는 벼랑 끝 상황을 훈련합니다.
    mosaic=1.0,        # (모자이크) 4장의 사진을 하나로 합쳐서, 좁은 화면 안에 여러 객체가 있는 복잡한 상황을 학습시킵니다.

    # ==========================================
    # 📐 3. 주행 역학 (회전, 찌그러짐) 증강
    # ==========================================
    degrees=10.0,      # (회전) 차체가 요철을 밟아 흔들리거나 카메라가 삐뚤어지게 달린 상황에 대비합니다.
    perspective=0.001, # (원근감) 표지판에 가까워질수록 3D 공간에서 렌즈에 투영되며 왜곡되는 뷰를 훈련합니다.
    shear=1.0,         # (기울임) 고속 코너링 시 사물이 순간적으로 옆으로 찌그러져 보이는 현상을 방어합니다.

    # ==========================================
    # ⛔ 4. 방향성 파괴 및 유령 현상 방지 (작동 금지 구역)
    # ==========================================
    fliplr=0.0,        # (좌우 반전 끄기) ❌ 왼쪽/오른쪽 표지판의 의미가 뒤바뀌는 대참사를 막기 위해 절대 금지합니다.
    flipud=0.0,        # (상하 반전 끄기) ❌ 현실에서 자동차가 뒤집히지 않는 한 발생하지 않으므로 꺼둡니다.
    erasing=0.0,       # (무작위 지우기 끄기) ❌ 화살표 머리가 지워져 '직진'으로 오인되거나 가장자리 표지판이 날아가는 것을 막습니다.
    mixup=0.0,         # (이미지 합성 끄기) ❌ 사진 두 장을 겹치면 표지판이 반투명한 유령처럼 변하므로 꺼둡니다.
    copy_paste=0.0,    # (복붙 합성 끄기) ❌ 부자연스러운 합성 배경이 학습에 방해될 수 있어 깔끔하게 제외합니다.

    
    # 📂 저장 위치 설정
    project='4WD_Final_Project',
    name='train_data_640'
)

print("✅ 학습이 성공적으로 시작되었습니다!")